public class Main {
    public static void main(String[] args) {
        int skor = 10;
        skor += 5;
        System.out.println(skor);
        skor *= 2;
        System.out.println(skor);
        skor--;
        System.out.println(skor);

        int x = 5;
        System.out.println(x++);
        System.out.println(x);
        System.out.println(++x);
    }
}