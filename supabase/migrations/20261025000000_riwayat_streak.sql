create table if not exists public.riwayat_streak (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  waktu timestamptz not null default now(),
  streak_lama int,
  tanggal_lama text,
  streak_baru int,
  tanggal_baru text,
  sebab text not null,
  versi_app text
);

alter table public.riwayat_streak enable row level security;

create policy "baca milik sendiri" on public.riwayat_streak
  for select using (auth.uid() = user_id);

create policy "tambah milik sendiri" on public.riwayat_streak
  for insert with check (auth.uid() = user_id);
